create table if not exists public.figures (
    id bigint generated by default as identity primary key,
    slug text not null unique,
    display_name text not null,
    full_name text,
    birth_year integer,
    death_year integer,
    short_description text,
    knowledge_cutoff_date date,
    is_active boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.sources (
    id bigint generated by default as identity primary key,
    figure_id bigint not null references public.figures(id) on delete cascade,
    source_key text not null unique,
    title text not null,
    author text,
    source_type text not null,
    source_level text not null,
    publication_date date,
    original_url text,
    rights_status text,
    rights_notes text,
    language text not null default 'English',
    source_owner text,
    approved_for_ingestion boolean not null default false,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists public.documents (
    id bigint generated by default as identity primary key,
    source_id bigint not null references public.sources(id) on delete cascade,
    file_name text not null,
    storage_path text,
    file_type text,
    checksum text,
    extraction_status text not null default 'pending',
    page_count integer,
    character_count integer,
    extraction_warning text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_sources_figure_id
    on public.sources(figure_id);

create index if not exists idx_documents_source_id
    on public.documents(source_id);
    
alter table public.figures enable row level security;
alter table public.sources enable row level security;
alter table public.documents enable row level security;

